"""Generate the DSH 0.2.2 preset bundle + the packages its presets mount.

WHY THIS EXISTS
    0.1.5 read user presets from `<DSH_HOME>/.agent-presets/<id>/` (a directory
    scan). 0.2.2's registry "neither scans directories nor accepts preset paths":
    a preset is a *bundle patch* that inserts an
    `@deepseek-ai/dsh-agent-preset` row, and the only supported way to change it
    is to install a bundle whose patch declares or overrides it.

    So `plugins/presets/<id>/{preset.yml,agent.cordis.yml}` becomes one row per
    preset inside `plugins/bundled/@dsh-vscode/presets/cordis.patch.yml`, with
    `agent.cordis.yml` embedded verbatim as the row's `config.plugins`.

    The router presets ALSO mount local ES modules (`router-bootstrap-*.mjs`,
    `gitbash-executor.mjs`). Those cannot stay relative: an inserted row's
    relative paths are anchored beside its patch file, but a preset's CHILD
    names are resolved from the profile (dsh-agent-preset-registry mounts the
    child tree with the profile's base URL), so `./x.mjs` would look for
    `<profile>/x.mjs`. dsh-doc's compositions reference says "resolve assets from
    installed packages rather than a preset directory" — so each entry module
    becomes a real package under `plugins/bundled/`, transplanted into the
    profile's node_modules, and the preset row names the package.

    Everything else in `plugins/presets/` is source of truth; this script is the
    only writer of the generated bundle and asset packages. Run it from the repo
    root: `python .smoke/gen-presets.py`.
"""
import json
import os
import shutil
import sys

ROOT = os.path.abspath(".")
SRC = os.path.join(ROOT, "plugins", "presets")
BUNDLED = os.path.join(ROOT, "plugins", "bundled")
BUNDLE = os.path.join(BUNDLED, "@dsh-vscode", "presets")

# Roster order: 0.2.2's shipped web presets occupy 1..4 (standard/ptc/minimal/
# cordis). Keep ours after them so the shipped roster stays on top.
ORDER_BASE = 10

# preset id -> [(generated package name, entry file in the preset dir), ...]
#
# These are the modules the presets mount by package name. Each generated
# package carries the WHOLE `.mjs` set of its preset directory (the entry module
# imports its siblings relatively, e.g. router-bootstrap-*.mjs -> router-core-*.mjs),
# with `main` pointing at the listed entry file.
ASSET_PACKAGES = {
    "router-standard": [
        ("dsh-preset-router-standard-bootstrap", "router-bootstrap-v34.mjs"),
        ("dsh-preset-router-standard-gitbash", "gitbash-executor.mjs"),
    ],
    "router-spec": [
        ("dsh-preset-router-spec-bootstrap", "router-bootstrap-v10.mjs"),
    ],
    "ppt-master": [],
}
# Packages this script used to generate; any other dsh-preset-* dir under
# plugins/bundled is not ours to delete.
GENERATED_PREFIX = "dsh-preset-"


def read_scalar(path, key):
    """Very small preset.yml reader: `key: value` lines, value may be quoted."""
    try:
        with open(path, encoding="utf-8") as handle:
            for line in handle:
                stripped = line.strip()
                if stripped.startswith(key + ":"):
                    value = stripped[len(key) + 1:].strip()
                    if value.startswith('"') and value.endswith('"'):
                        return json.loads(value)
                    return value
    except OSError:
        pass
    return ""


def indent_block(text, spaces):
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else "" for line in text.splitlines())


def write_package(name, entry, preset_dir):
    """Create plugins/bundled/<name>/ with the preset directory's .mjs payload."""
    target = os.path.join(BUNDLED, name)
    staging = target + ".tmp"
    shutil.rmtree(staging, ignore_errors=True)
    os.makedirs(staging)
    assets = sorted(entry_file for entry_file in os.listdir(preset_dir) if entry_file.endswith(".mjs"))
    if entry not in assets:
        sys.exit(f"{preset_dir}: entry module {entry} is missing")
    for asset in assets:
        shutil.copyfile(os.path.join(preset_dir, asset), os.path.join(staging, asset))
    with open(os.path.join(staging, "package.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps({
            "name": name,
            "version": "1.0.0",
            "private": True,
            "type": "module",
            "main": "./" + entry,
            "description": "Router preset module packaged for the 0.2.2 preset bundle (generated by .smoke/gen-presets.py)",
        }, indent=2, ensure_ascii=False) + "\n")
    shutil.rmtree(target, ignore_errors=True)
    os.rename(staging, target)
    return name


def main():
    if not os.path.isdir(SRC):
        sys.exit("missing source directory " + SRC)

    rows = []
    generated_assets = []
    for index, preset_id in enumerate(sorted(name for name in os.listdir(SRC) if os.path.isdir(os.path.join(SRC, name)))):
        preset_dir = os.path.join(SRC, preset_id)
        agent_path = os.path.join(preset_dir, "agent.cordis.yml")
        if not os.path.isfile(agent_path):
            print(f"skip {preset_id}: no agent.cordis.yml")
            continue
        with open(agent_path, encoding="utf-8") as handle:
            children = handle.read().rstrip("\n")
        if "name: ./" in children:
            sys.exit(
                f"{agent_path} still mounts a relative module (name: ./...). A preset's child names are "
                "resolved from the profile, not anchored to the patch file — package the module under "
                "plugins/bundled/ and reference the package name (see ASSET_PACKAGES)."
            )
        for package_name, entry in ASSET_PACKAGES.get(preset_id, []):
            write_package(package_name, entry, preset_dir)
            generated_assets.append(package_name)
        display = read_scalar(os.path.join(preset_dir, "preset.yml"), "name") or preset_id
        description = read_scalar(os.path.join(preset_dir, "preset.yml"), "description")
        rows.append("\n".join([
            f"    - id: preset-{preset_id}",
            "      name: '@deepseek-ai/dsh-agent-preset'",
            "      config:",
            f"        id: {preset_id}",
            f"        name: {json.dumps(display, ensure_ascii=False)}",
            f"        description: {json.dumps(description, ensure_ascii=False)}",
            f"        order: {ORDER_BASE + index}",
            "        plugins:",
            indent_block(children, 10),
        ]))
    if not rows:
        sys.exit("no presets found under " + SRC)

    # Drop asset packages this script generated earlier but no longer needs.
    for entry in os.listdir(BUNDLED):
        if entry.startswith(GENERATED_PREFIX) and entry not in generated_assets:
            shutil.rmtree(os.path.join(BUNDLED, entry), ignore_errors=True)
            print("removed stale generated package " + entry)

    staging = BUNDLE + ".tmp"
    shutil.rmtree(staging, ignore_errors=True)
    os.makedirs(staging)
    header = [
        "# GENERATED by .smoke/gen-presets.py from plugins/presets/<id>/ — do not edit.",
        "#",
        "# 0.2.2's preset registry reads declarations from bundle patches only: it no",
        "# longer scans <DSH_HOME>/.agent-presets/. Each row is one legacy preset",
        "# directory (preset.yml + agent.cordis.yml), with agent.cordis.yml embedded",
        "# verbatim as config.plugins. Local ES modules those lists mount are separate",
        "# packages under plugins/bundled/ (dsh-preset-*), because a preset's child",
        "# names resolve from the profile rather than the patch file.",
        "",
        "- insert:",
    ]
    with open(os.path.join(staging, "cordis.patch.yml"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(header) + "\n" + "\n".join(rows) + "\n")
    with open(os.path.join(staging, "package.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps({
            "name": "@dsh-vscode/presets",
            "version": "1.0.0",
            "private": True,
            "type": "module",
            "description": "Baked agent presets (router-standard, router-spec, ppt-master) as 0.2.2 bundle declarations",
            "dsh": {"bundle": {"patch": "./cordis.patch.yml"}},
        }, indent=2, ensure_ascii=False) + "\n")
    shutil.rmtree(BUNDLE, ignore_errors=True)
    os.rename(staging, BUNDLE)
    print(f"wrote {BUNDLE}: {len(rows)} preset row(s); asset packages: {', '.join(generated_assets) or '(none)'}")


if __name__ == "__main__":
    main()
