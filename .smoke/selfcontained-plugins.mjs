  "dsh-zh-kit": "npm dsh-zh-kit@0.1.2 (Chinese UI kit)",
  "@dsh-vscode/presets": "generated by .smoke/gen-presets.py from plugins/presets/ (0.2.2 bundle declaring the router-standard/router-spec/ppt-master presets)"
